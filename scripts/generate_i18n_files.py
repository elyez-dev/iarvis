def get_display_name(code: str, target_code: str, en_name: str) -> str:
    """Get the display name for code as seen from target_code locale.
    
    If it's the language itself, try to use the native name.
    Otherwise, use the English name (the t() fallback handles proper i18n).
    """
    if code == target_code:
        return NATIVE_NAMES.get(code, en_name)
    return en_name


def generate_translations():
    codes = load_language_codes()
    template = load_en_template()
    
    os.makedirs(I18N_DIR, exist_ok=True)
    
    preserve = {"en", "es"}
    for code in codes:
        filename = f"{code}.json"
        filepath = os.path.join(I18N_DIR, filename)

        if code in preserve:
            print(f"  {filename}  SKIP (preserved)")
            continue

        # Start from template
        translations = {}
        
        # Copy UI strings in English (the t() fallback handles missing keys)
        for key, value in template.items():
            if key == "language_names":
                continue
            translations[key] = value
        
        # Build language_names for this locale
        lang_names = {}
        for lc in codes:
            en_name = get_english_name(lc)
            display = get_display_name(lc, code, en_name)
            lang_names[lc] = display
        
        translations["language_names"] = lang_names
        
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(translations, f, ensure_ascii=False, indent=2)
            f.write("\n")
        
        print(f"  {filename}  ({get_english_name(code)})")
    
    print(f"\n✅ Generated {len(codes)} translation files in {I18N_DIR}")


if __name__ == "__main__":
    generate_translations()
